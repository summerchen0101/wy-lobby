/**
 * Reads WordData/WordData.txt and generates web/src/wordData/wordData.generated.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..", "..");
const inputPath = join(root, "WordData", "WordData.txt");
const outputPath = join(__dirname, "..", "src", "wordData", "wordData.generated.ts");

const raw = readFileSync(inputPath, "utf8");
const parsed = JSON.parse(raw);

const entries = Object.entries(parsed)
  .map(([k, v]) => [Number(k), String(v)])
  .sort((a, b) => a[0] - b[0]);

const lines = entries.map(([id, text]) => {
  const escaped = JSON.stringify(text);
  return `  ${id}: ${escaped},`;
});

const output = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-word-data.mjs — do not edit manually.
// Source: WordData/WordData.txt

export const WORD_DATA: Readonly<Record<number, string>> = {
${lines.join("\n")}
};
`;

writeFileSync(outputPath, output, "utf8");
console.log(`Generated ${outputPath} (${entries.length} entries)`);
