/**
 * Reads HeadPicData + ItemData JSON and generates
 * web/src/features/lobby/profileAvatarData.generated.ts
 *
 * Sort by HeadPicData.Order; image from ItemData.Icon via ItemID.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const webRoot = join(__dirname, "..");
const monorepoRoot = join(webRoot, "..");
const outputPath = join(
  webRoot,
  "src",
  "features",
  "lobby",
  "profileAvatarData.generated.ts",
);

const headPicCandidates = [
  join(monorepoRoot, "HeadPicData_C (1).txt"),
  join(monorepoRoot, "HeadPicData_C.txt"),
  join(webRoot, "HeadPicData_C.txt"),
];

const itemDataCandidates = [
  join(monorepoRoot, "ItemData_C (1).txt"),
  join(monorepoRoot, "ItemData_C.txt"),
  join(webRoot, "ItemData_C.txt"),
];

const headPicPath = headPicCandidates.find((p) => existsSync(p));
const itemDataPath = itemDataCandidates.find((p) => existsSync(p));

if (!headPicPath || !itemDataPath) {
  if (existsSync(outputPath)) {
    console.log(
      `Skip profile avatar data generation: source not found; using existing ${outputPath}`,
    );
    process.exit(0);
  }
  throw new Error(
    `Profile avatar sources not found. HeadPic: ${headPicCandidates.join(", ")}; ItemData: ${itemDataCandidates.join(", ")}`,
  );
}

/** Item Type 5 = player head portrait (see ItemData_C). */
const HEAD_ITEM_TYPE = 5;

const headPicRows = JSON.parse(readFileSync(headPicPath, "utf8"));
const itemRows = JSON.parse(readFileSync(itemDataPath, "utf8"));

const iconByItemId = new Map();
for (const row of itemRows) {
  if (row.Type !== HEAD_ITEM_TYPE) continue;
  const itemId = Number(row.ID);
  const icon = String(row.Icon ?? "").trim();
  if (!Number.isFinite(itemId) || !icon) continue;
  iconByItemId.set(itemId, icon);
}

const headItemIconLines = [...iconByItemId.entries()]
  .sort((a, b) => a[0] - b[0])
  .map(([id, icon]) => `  ${id}: ${JSON.stringify(icon)},`);

const rows = headPicRows
  .map((row) => {
    const headPicId = Number(row.ID);
    const itemId = Number(row.ItemID);
    const gender = Number(row.Gender);
    const order = Number(row.Order);
    if (
      !Number.isFinite(headPicId) ||
      !Number.isFinite(itemId) ||
      !Number.isFinite(order)
    ) {
      return null;
    }
    const icon = iconByItemId.get(itemId) ?? "";
    if (!icon) {
      console.warn(
        `HeadPic itemId ${itemId} (headPicId ${headPicId}) missing ItemData Icon`,
      );
    }
    return {
      headPicId,
      itemId,
      gender,
      order,
      icon,
    };
  })
  .filter(Boolean)
  .sort((a, b) => a.order - b.order);

if (rows.length === 0) {
  throw new Error("No HeadPic rows parsed from source data");
}

const rowLines = rows.map((r) => {
  return `  { headPicId: ${r.headPicId}, itemId: ${r.itemId}, gender: ${r.gender}, order: ${r.order}, icon: ${JSON.stringify(r.icon)} },`;
});

const headPicLabel = headPicPath.startsWith(monorepoRoot)
  ? headPicPath.slice(monorepoRoot.length + 1)
  : headPicPath.slice(webRoot.length + 1);
const itemLabel = itemDataPath.startsWith(monorepoRoot)
  ? itemDataPath.slice(monorepoRoot.length + 1)
  : itemDataPath.slice(webRoot.length + 1);

const output = `// AUTO-GENERATED by scripts/generate-profile-avatar-data.mjs — do not edit manually.
// Sources: ${headPicLabel}, ${itemLabel}

export type ProfileAvatarDataRow = {
  /** HeadPicData.ID */
  headPicId: number;
  /** ItemData.ID (wire AvatarID) */
  itemId: number;
  /** 1 = male, 2 = female */
  gender: number;
  /** HeadPicData.Order — display sort */
  order: number;
  /** ItemData.Icon e.g. head_15 — avatar image file stem */
  icon: string;
};

export const PROFILE_AVATAR_ROWS: readonly ProfileAvatarDataRow[] = [
${rowLines.join("\n")}
];

/** All ItemData Type 5 head icons (includes ids outside HeadPicData). */
export const HEAD_ITEM_ICON_BY_ID: Readonly<Record<number, string>> = {
${headItemIconLines.join("\n")}
};
`;

writeFileSync(outputPath, output, "utf8");
console.log(
  `Generated ${outputPath} from ${headPicLabel} + ${itemLabel} (${rows.length} rows)`,
);
